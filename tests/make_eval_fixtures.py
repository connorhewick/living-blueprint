#!/usr/bin/env python3
"""Rewrite each eval case's fixture.sh from tests/fixtures/shop. An eval run starts in an empty
directory with no access to this checkout, so the script has to carry the files itself."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import blueprint as bp  # noqa: E402

SHOP = ROOT / "tests" / "fixtures" / "shop"
CASES = ("map-writes-a-valid-doc", "design-asks-before-writing", "build-refuses-unapproved", "drift-reports-before-editing")
END = "LB_FIXTURE_END"


def script(case: str) -> str:
    lines = ["#!/usr/bin/env bash", "# Generated by tests/make_eval_fixtures.py. Do not edit.", "set -euo pipefail"]
    files = sorted(p for p in SHOP.rglob("*") if p.is_file() and p.suffix != ".html")
    code = [p for p in files if "docs" not in p.relative_to(SHOP).parts]
    docs = [] if case in ("map-writes-a-valid-doc", "design-asks-before-writing") else [p for p in files if p not in code]

    def write(paths):
        for path in paths:
            name = path.relative_to(SHOP).as_posix()
            text = path.read_text(encoding="utf-8").rstrip("\n")
            assert END not in text
            lines.append(f"mkdir -p \"$(dirname '{name}')\"")
            lines.append(f"cat > '{name}' <<'{END}'\n{text}\n{END}")

    git = "git -c user.name=eval -c user.email=eval@example.invalid"
    write(code)
    lines += ["git init -q -b main", f"{git} add -A .", f"{git} commit -qm code"]
    write(docs)
    if case == "drift-reports-before-editing":
        # pin the doc to the first commit, then break the rule it records
        lines.append(
            "python3 - <<'PY'\nimport json,subprocess\np='docs/architecture/shop.json'\nd=json.load(open(p))\n"
            "d['commit']=subprocess.check_output(['git','rev-parse','--short=12','HEAD'],text=True).strip()\n"
            "json.dump(d,open(p,'w'),indent=2)\nPY"
        )
        lines.append(
            "cat > api/admin.py <<'PY'\nfrom api.repository import OrderRepository\n\n\n"
            "def force_order(cart_id: str):\n    return OrderRepository().insert(cart_id, status=\"shipped\")\nPY"
        )
        lines.append(
            "python3 - <<'PY'\np='api/orders.py'\ns=open(p).read().replace('    def find(','    def count(self):\\n        return 0\\n\\n    def find(')\nopen(p,'w').write(s)\nPY"
        )
        lines += [f"{git} add -A api", f"{git} commit -qm 'add an admin path that writes orders directly'"]
    if docs:
        lines += [f"{git} add -A docs", f"{git} commit -qm docs"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    for case in CASES:
        folder = ROOT / "evals" / case
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "fixture.sh").write_text(script(case), encoding="utf-8")
